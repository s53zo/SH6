import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {multiplierFocusedQsos} from '../modules/multipliers/overview-model.js';
vm.runInThisContext(fs.readFileSync(new URL('../cqww-ms-audit.js',import.meta.url),'utf8'));
const api=globalThis.SH6CqwwMsAudit;
const meta={contestId:'CQ-WW-SSB',categoryOperator:'MULTI-OP',categoryTransmitter:'ONE'};
const source='START-OF-LOG: 3.0\n';
const q=(minute,band='20M',id='0',extra={})=>({ts:Date.UTC(2026,9,24,0,minute),band,txId:id,call:'K1AA',country:'United States',cqZone:5,...extra});
const build=(qs,raw=source)=>api.build(qs,meta,raw);
assert.ok(api.applicable(meta));
for(const extra of [{contestId:'CQ-WPX-SSB'},{contestId:'CQ-WW-RTTY'},{categoryOperator:'SINGLE-OP'},{categoryTransmitter:'TWO'},{categoryStation:'DISTRIBUTED'}]) assert.equal(api.applicable({...meta,...extra}),false);
assert.ok(api.applicable({...meta,categoryOperator:'M/S',categoryTransmitter:''}));
assert.equal(build([q(0)],'ADIF').checked,false);
assert.equal(build([q(0,'20M','0',{ts:Date.UTC(2025,9,25)})]).checked,false);
assert.equal(build([]).checked,false);
let m=build([q(0),q(5),q(9,'15M')]);
assert.equal(m.findings.filter(f=>f.kind==='Timing').length,1);
assert.equal(m.findings.find(f=>f.kind==='Timing').allowed,Math.floor(q(10).ts/60000));
assert.equal(build([q(0),q(5),q(10,'15M')]).findings.length,0,'clock starts at first, not last QSO');
assert.equal(build([q(59),q(69,'15M')]).findings.length,0,'clock crosses hours');
assert.equal(build([q(0,'20M','0',{ts:q(0).ts+59000}),q(10,'15M')]).findings.length,0,'Cabrillo whole-minute policy');
m=build([q(0),q(3,'10M','1',{country:'Japan',cqZone:25}),q(10,'15M'),q(13,'40M','1',{country:'Canada',cqZone:4})]);
assert.equal(m.findings.filter(f=>f.kind==='Timing').length,0,'independent clocks');
assert.equal(m.periods.length,4);
m=build([q(0),q(1,'20M','1')]);
assert.ok(m.findings.some(f=>f.kind==='Multiplier' && /No new/.test(f.detail)),'earlier RUN credits count');
assert.ok(!m.findings.some(f=>/observed RUN band/.test(f.detail)),'inferred same-band overlap is not displayed');
m=build([q(0),q(1,'20M','1',{country:'Canada',cqZone:5})]);
assert.equal(m.findings.filter(f=>f.kind==='Multiplier').length,0,'new country alone qualifies');
m=build([q(0),q(1,'20M','1',{cqZone:4})]);
assert.equal(m.findings.filter(f=>f.kind==='Multiplier').length,0,'new zone alone qualifies');
m=build([q(0,'20M','1',{country:null,cqZone:null})]);
assert.ok(m.findings.some(f=>f.kind==='Multiplier' && /Cannot establish/.test(f.detail)));
m=build([q(0),q(0,'20M','1')]);
assert.ok(m.findings.some(f=>f.kind==='Multiplier' && /ambiguous/.test(f.detail)),'same-minute multiplier tie');
m=build([q(0,'20M','0',{country:'United States',cqZone:5}),q(0,'20M','1',{country:'United States',cqZone:4})]);
assert.equal(m.findings.filter(f=>f.kind==='Multiplier').length,0,'unique new zone qualifies despite tied country');
m=build([q(0,'20M','1',{country:null,cqZone:undefined,exchRcvd:'25'})]);
assert.equal(m.findings.filter(f=>f.kind==='Multiplier').length,0,'Cabrillo received zone is usable without country resources');
m=build([q(0),q(9,'15M')],source+'X-QSO: test');
assert.equal(m.findings.filter(f=>f.kind==='Timing').length,0);
assert.ok(m.findings.some(f=>f.kind==='Review'));
assert.equal(m.xCount,1);
m=build([q(0),q(3,'10M',''),q(9,'15M')]);
assert.ok(m.findings.some(f=>f.kind==='Data'));
assert.equal(m.findings.filter(f=>f.kind==='Timing').length,0,'missing IDs downgrade timing');
m=build([q(0,'Unknown'),q(1,'20M','1')]);
assert.ok(m.findings.some(f=>f.kind==='Multiplier' && /Cannot establish/.test(f.detail)),'unplaced earlier evidence prevents definite multiplier eligibility');
m=build([q(0),q(0,'15M'),q(9,'40M')]);
assert.equal(m.findings.length,0,'same-minute band ambiguity is not a displayed finding');
assert.doesNotMatch(api.render(m),/Different bands share the same minute|Ordering and lock timing/);
assert.equal(m.findings.filter(f=>f.kind==='Timing').length,0,'same-minute bands are ambiguous');
m=build([q(0),q(5,'15M'),q(7,'10M')]);
assert.equal(m.findings.filter(f=>f.kind==='Timing').length,1);
assert.ok(m.findings.some(f=>f.kind==='Review' && /Provisional/.test(f.detail)),'do not assert cascading violations');
const v26bSequence=[
 q(85,'160M','1',{call:'OE6MMD',country:'Austria',cqZone:15}),
 q(85,'40M','0',{call:'VU2IVV',country:'India',cqZone:22}),
 q(99,'40M','1',{call:'VU22CW',country:'India',cqZone:22}),
 q(99,'40M','0',{call:'N7US'}),
 q(104,'80M','1',{call:'V26B',country:'Antigua & Barbuda',cqZone:8})
];
m=build(v26bSequence);
assert.ok(m.findings.some(f=>f.index===2 && f.kind==='Multiplier'),'retain questionable VU22CW eligibility');
assert.ok(!m.findings.some(f=>f.index===4),'V26B is not early against a phantom 01:39 clock');
assert.deepEqual(m.periods.filter(p=>p.id==='1').map(p=>p.band),['160M','80M']);
assert.equal(m.periods.find(p=>p.id==='1' && p.band==='80M').start,Math.floor(q(104).ts/60000));
m=build([q(0,'160M','1'),q(3,'40M','1',{country:null,cqZone:null}),q(5,'80M','1',{country:'Japan',cqZone:25})]);
assert.ok(m.findings.some(f=>f.index===2 && f.kind==='Review' && f.start===Math.floor(q(0).ts/60000)),'real early change remains reviewable against the established clock');
assert.equal(m.periods.filter(p=>p.id==='1').length,2,'unresolved multiplier cannot start an observed lock');
assert.doesNotMatch(api.render(build([q(0,'20M','1',{country:null,cqZone:null})])),/1970-/,'uncheckable MULT-only logs retain actual observation times');
const list=[q(0),q(9,'15M',{toString:()=> '0'},{call:'<img onerror=x>'})];
const before=JSON.stringify(list);m=build(list);
assert.equal(JSON.stringify(list),before);
const html=api.render(m,list);
assert.ok(html.includes('Full-log audit') && html.includes('Independent ten-minute locks'));
assert.ok(html.includes('&lt;img') && !html.includes('<img onerror'));
assert.ok(html.includes('data-index="1"'));
assert.ok(html.includes('cqww-ms-case') && html.includes('15 minutes before and after'));
const contextList=[q(14),q(15),q(30),q(45),q(46)];
const slot={fullQsoData:{qsos:contextList},logVersion:4};

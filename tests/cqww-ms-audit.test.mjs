assert.deepEqual(multiplierFocusedQsos(slot,focus,'A'),[],'do not leak another comparison slot');
assert.deepEqual(multiplierFocusedQsos(slot,{...focus,logVersion:3},'B'),[],'reject stale source');
assert.deepEqual(multiplierFocusedQsos(slot,{...focus,contextMinutes:undefined},'B'),[contextList[2]],'ordinary multiplier drilldown remains exact');
assert.doesNotMatch(html,/MULT contact on the observed RUN band/);
console.log('CQWW M/S model tests PASS');
